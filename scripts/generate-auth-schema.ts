/**
 * Generates the identity module's authentication schema.
 *
 * Better Auth's CLI cannot reach Cloudflare D1 (it is only queryable from a
 * Worker), so the schema is produced here against Node's built-in SQLite using
 * exactly the same auth configuration the application uses. The resulting SQL is
 * committed as a reviewed migration and applied with `wrangler d1 migrations`.
 *
 * Run: node scripts/generate-auth-schema.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";

import { getMigrations } from "better-auth/db/migration";

import { createAuth } from "../src/modules/identity/auth-options.ts";
import { createUnconfiguredMailer } from "../src/modules/identity/email.ts";

// Defaults to the original identity migration. Pass a path to generate into a
// scratch file when diffing a configuration change before writing a new
// migration (applied migrations are never rewritten).
const OUTPUT = process.argv[2] ?? "migrations/0001_identity_authentication.sql";

const db = new DatabaseSync(":memory:");
const auth = createAuth({
  database: db,
  secret: "schema-generation-only-secret-32-chars",
  baseURL: "http://localhost:3000",
  isProduction: false,
  mailer: createUnconfiguredMailer(),
});

const { runMigrations } = await getMigrations(auth.options);
await runMigrations();

// Tables must precede indexes: a migration runs statements in order.
const rows = db
  .prepare(
    "SELECT name, type, sql FROM sqlite_master WHERE type IN ('table', 'index') AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name",
  )
  .all() as { name: string; type: string; sql: string }[];

const header = `-- Identity authentication schema, generated by scripts/generate-auth-schema.ts.
-- Source of truth: src/modules/identity/auth-options.ts (Better Auth 1.7.22).
-- Regenerate after any auth configuration change and review the diff.
-- D1 limitation: the adapter runs with transaction=false, so migrations and
-- multi-statement auth writes are not transactional. See docs/decisions/0008.

`;

const body = rows.map((row) => `${row.sql};`).join("\n\n");
mkdirSync("migrations", { recursive: true });
writeFileSync(OUTPUT, `${header}${body}\n`, "utf8");

console.log(`Wrote ${rows.length} statements to ${OUTPUT}`);
for (const row of rows) console.log(` - ${row.name}`);
